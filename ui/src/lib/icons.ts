/** Sidebar and table icon for each scanner category (keys are Rust's `Category` variant names). */
const CATEGORY_ICONS: Record<string, IconComponent> = {
  RecycleBin: TrashIcon,
  UserTemp: ClockCounterClockwiseIcon,
  SystemTemp: ClockCounterClockwiseIcon,
  WindowsUpdate: DownloadSimpleIcon,
  CrashDumps: BugIcon,
  WindowsLogs: WindowsLogoIcon,
  OldWindows: ArchiveIcon,
  BrowserCache: GlobeIcon,
  AppCache: AppWindowIcon,
  ThumbnailCache: ImageIcon,
  GpuCache: CpuIcon,
  DevCache: PackageIcon,
  NodeModules: CubeIcon,
  BuildArtifacts: HammerIcon,
  PythonEnv: CodeIcon,
  LogFiles: FileTextIcon,
  LargeFiles: FileIcon,
  Custom: FolderIcon,
  AppLeftovers: FolderDashedIcon,
};

export function categoryIcon(category: string): IconComponent {
  return CATEGORY_ICONS[category] ?? FolderIcon;
}
